import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = fileURLToPath(new URL('../', import.meta.url));
const dir = 'docs/evidence/config-proof-measurement-20261027';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const read = file => fs.readFile(path.resolve(root, file));
const index = JSON.parse(await read(`${dir}/index.json`));
assert.equal(index.parent, 'b8f7b268cde63c0a0d12032f278b442933405839');
for (const [file, sha] of Object.entries(index.files)) assert.equal(hash(await read(file)), sha, file);
const report = JSON.parse(await read(`${dir}/validation.json`));
assert.equal(report.externalModelCalls, 0);
assert.equal(report.rounds, 6);
assert.ok(report.raw.elapsedMs > report.audited.elapsedMs);
assert.ok(report.detached.elapsedMs > report.audited.elapsedMs);
assert.deepEqual(report.bundleSha256, JSON.parse(await read(`${dir}/validation.json`)).bundleSha256);
console.log(JSON.stringify({ status: 'verified', files: Object.keys(index.files).length, rounds: report.rounds, externalModelCalls: 0, productionDiff: [] }));
